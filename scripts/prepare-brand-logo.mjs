import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';

// Explicit local import. Website builds use the checked-in assets, not native tools.
const source = resolve(process.argv[2] ?? `${process.env.HOME}/Downloads/SCUBA LAK Diver Logo Restoration.png`);
const temporary = resolve('tmp/brand-logo');
const destination = 'public/media/brand';
mkdirSync(destination, { recursive: true });
execFileSync('swift', ['scripts/prepare-brand-logo.swift', source, temporary], { stdio: 'inherit' });
const fingerprint = data => createHash('sha256').update(data).digest('hex').slice(0, 12);
const assets = {};
let total = 0;
for (const size of [16, 32, 48, 96, 180, 192, 512]) {
  const data = readFileSync(join(temporary, `logo-${size}.png`));
  const name = `scuba-lak-round-${size}-${fingerprint(data)}.png`;
  writeFileSync(join(destination, name), data);
  assets[size] = `media/brand/${name}`;
  total += data.length;
}

// PNG-backed ICO entries retain the same transparent round corners at 16/32/48px.
const sizes = [16, 32, 48];
const pngs = sizes.map(size => readFileSync(join(temporary, `logo-${size}.png`)));
const header = Buffer.alloc(6 + sizes.length * 16);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(sizes.length, 4);
let offset = header.length;
sizes.forEach((size, index) => {
  const position = 6 + index * 16;
  header[position] = size;
  header[position + 1] = size;
  header.writeUInt16LE(1, position + 4);
  header.writeUInt16LE(32, position + 6);
  header.writeUInt32LE(pngs[index].length, position + 8);
  header.writeUInt32LE(offset, position + 12);
  offset += pngs[index].length;
});
const ico = Buffer.concat([header, ...pngs]);
const icoName = `scuba-lak-round-${fingerprint(ico)}.ico`;
writeFileSync(join(destination, icoName), ico);
const metadata = {
  logoSrc: assets[96],
  logoSrcset: `${assets[96]} 96w, ${assets[192]} 192w`,
  faviconSrc: assets[48],
  favicon96: assets[96],
  faviconIco: `media/brand/${icoName}`,
  appleTouchIcon: assets[180],
  appIcon192: assets[192],
  appIcon512: assets[512],
  organizationLogo: assets[512]
};
writeFileSync('src/app/data/brand-assets.generated.ts', `// Generated by scripts/prepare-brand-logo.mjs from the supplied restored artwork.\nexport const BRAND_ASSETS = ${JSON.stringify(metadata, null, 2)} as const;\n`);
console.log(JSON.stringify(metadata, null, 2));
console.log(`Prepared circular brand assets: ${((total + ico.length) / 1024).toFixed(1)} KB total.`);
