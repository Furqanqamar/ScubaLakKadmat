import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, renameSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Explicit local import only. Existing photos, films and source uploads are untouched.
const sourceRoot = resolve(process.argv[2] ?? `${process.env.HOME}/Downloads`);
const manifestPath = fileURLToPath(new URL('./additional-photos.json', import.meta.url));
const entries = JSON.parse(readFileSync(manifestPath, 'utf8'));
const output = 'public/media/originals';
const temporary = resolve('tmp/additional-photos');
mkdirSync(output, { recursive: true });
mkdirSync(temporary, { recursive: true });
const run = (command, args) => execFileSync(command, args, { stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 20 * 1024 * 1024 });
run('swift', ['scripts/convert-original-photos.swift', sourceRoot, temporary, manifestPath]);
const assets = {}, imageInfo = {};
let sourceBytes = 0, deliveryBytes = 0;
for (const entry of entries) {
  sourceBytes += statSync(join(sourceRoot, entry.file)).size;
  const png = join(temporary, `${entry.id}.png`);
  const dimensions = run('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', png]).toString();
  const width = Number(dimensions.match(/pixelWidth: (\d+)/)[1]);
  const height = Number(dimensions.match(/pixelHeight: (\d+)/)[1]);
  const variants = [];
  for (const targetWidth of [...new Set([480, 800, width].filter(size => size <= width))]) {
    const file = join(temporary, `${entry.id}-${targetWidth}.webp`);
    run('cwebp', ['-quiet', '-q', '90', '-m', '6', '-sharp_yuv', '-metadata', 'none', '-resize', String(targetWidth), '0', png, '-o', file]);
    const hash = createHash('sha256').update(readFileSync(file)).digest('hex').slice(0, 12);
    const name = `${entry.id}-${targetWidth}-${hash}.webp`;
    renameSync(file, join(output, name));
    deliveryBytes += statSync(join(output, name)).size;
    variants.push({ width: targetWidth, url: `media/originals/${name}` });
  }
  const placeholderPath = join(temporary, `${entry.id}-placeholder.webp`);
  run('cwebp', ['-quiet', '-q', '40', '-metadata', 'none', '-resize', '24', '0', png, '-o', placeholderPath]);
  const imageUrl = variants.at(-1).url;
  assets[entry.id] = { id: entry.id, kind: 'image', title: entry.title, description: entry.description, location: entry.location, category: entry.category, imageUrl, width, height, size: entry.size ?? (height > width ? 'tall' : 'wide') };
  imageInfo[imageUrl] = { width, height, srcset: variants.map(item => `${item.url} ${item.width}w`).join(', '), placeholder: `data:image/webp;base64,${readFileSync(placeholderPath).toString('base64')}`, objectPosition: entry.objectPosition };
  console.log(`Prepared ${entry.id}: ${width}×${height}`);
}
// Reproducible generated data: deploys never require the original uploads or native tools.
writeFileSync('src/app/data/additional-media.generated.ts', `// Generated by scripts/import-additional-photos.mjs. Captions: scripts/additional-photos.json.\nimport { GalleryItem } from '../models/site-data.model';\nexport const ADDITIONAL_MEDIA = ${JSON.stringify(assets, null, 2)} as const satisfies Readonly<Record<string, GalleryItem>>;\n`);
writeFileSync('src/app/data/additional-image-info.generated.ts', `// Generated responsive metadata; original uploads and EXIF are not embedded.\nimport type { OriginalImageInfo } from './original-image-info.generated';\nexport const ADDITIONAL_IMAGE_INFO: Readonly<Record<string, OriginalImageInfo & { readonly objectPosition: string }>> = ${JSON.stringify(imageInfo, null, 2)};\n`);
console.log(`Imported ${entries.length} photos: ${(sourceBytes / 1048576).toFixed(1)} MB source; ${(deliveryBytes / 1048576).toFixed(1)} MB across all responsive sizes.`);
