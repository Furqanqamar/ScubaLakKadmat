import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const sharp = require('sharp');
const root = new URL('../', import.meta.url);
const target = new URL('public/media/islands/', root);
await mkdir(target, { recursive: true });
const brief = JSON.parse(await readFile(new URL('output/island-illustrations/generation-brief.json', root), 'utf8'));
const photos = JSON.parse(await readFile(new URL('./island-photos.json', import.meta.url), 'utf8'));
const media = {};
const sources = new URL('../tmp/island-photo-sources/', import.meta.url);
await mkdir(sources, { recursive: true });
async function prepare(id, input, extra = {}) {
  const metadata = await sharp(input).metadata();
  const maxWidth = Math.min(metadata.width, id.endsWith('-photo') ? 1440 : 1086);
  const widths = [...new Set([360, 640, maxWidth].filter(width => width <= maxWidth))];
  const variants = [];
  for (const width of widths) {
    const buffer = await sharp(input).rotate().resize({ width, withoutEnlargement: true }).webp({ quality: 88, effort: 6 }).toBuffer({ resolveWithObject: true });
    const hash = createHash('sha256').update(buffer.data).digest('hex').slice(0, 12);
    const file = `${id}-${width}-${hash}.webp`;
    await writeFile(new URL(file, target), buffer.data);
    variants.push({ src: `media/islands/${file}`, width: buffer.info.width, height: buffer.info.height, bytes: buffer.data.length });
  }
  const main = variants.at(-1);
  const placeholder = await sharp(input).rotate().resize({ width: 24 }).blur(1).webp({ quality: 40 }).toBuffer();
  media[id] = { src: main.src, width: main.width, height: main.height, srcset: variants.map(image => `${image.src} ${image.width}w`).join(', '), placeholder: `data:image/webp;base64,${placeholder.toString('base64')}`, ...extra };
  console.log(`${id}: ${variants.map(image => `${image.width}w ${Math.round(image.bytes / 1024)}KB`).join(' / ')}`);
}
// Generated masters remain outside public/. Only responsive delivery assets ship.
for (const item of brief.islands) await prepare(item.id, await readFile(new URL(`output/island-illustrations/${item.id}-island.webp`, root)));
for (const photo of photos) {
  const sourceHash = createHash('sha256').update(photo.url).digest('hex').slice(0, 8);
  const source = new URL(`${photo.id}-${sourceHash}.jpg`, sources);
  let input;
  try { input = await readFile(source); }
  catch {
    let response;
    for (let attempt = 0; attempt < 3; attempt++) {
      response = await fetch(photo.url, { headers: { 'User-Agent': 'ScubaLakIslandGuide/1.0 (licensed image import)' } });
      if (response.status !== 429) break;
      const delay = Math.max(20, Number(response.headers.get('retry-after')) || 0);
      console.log(`Photo host requested backoff: ${photo.id}, ${delay}s`);
      await new Promise(resolve => setTimeout(resolve, delay * 1000));
    }
    if (!response.ok) throw new Error(`Photo import failed: ${photo.id} (${response.status})`);
    input = Buffer.from(await response.arrayBuffer());
    await writeFile(source, input);
    await new Promise(resolve => setTimeout(resolve, 1500));
  }
  await prepare(photo.id, input, { caption: photo.caption, credit: photo.credit, license: photo.license, licenseUrl: photo.licenseUrl, sourceUrl: `https://commons.wikimedia.org/wiki/${encodeURIComponent(photo.title.replaceAll(' ', '_'))}` });
}
await writeFile(new URL('src/app/data/island-media.generated.ts', root), `// Generated by scripts/prepare-island-media.mjs. Do not edit.\nimport { IslandMedia } from '../models/island-guide.model';\nexport const ISLAND_MEDIA: Readonly<Record<string, IslandMedia>> = ${JSON.stringify(media, null, 2)};\n`);
