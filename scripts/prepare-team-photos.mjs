import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, renameSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Import supplied team portraits without modifying the source uploads.
const source = resolve(process.argv[2] ?? `${process.env.HOME}/Downloads`);
const manifest = fileURLToPath(new URL('./team-photos.json', import.meta.url));
const entries = JSON.parse(readFileSync(manifest, 'utf8'));
const temporary = resolve('tmp/team-photos');
const output = 'public/media/originals';
mkdirSync(output, { recursive: true });
const run = (command, args) => execFileSync(command, args, { stdio: ['ignore', 'pipe', 'pipe'] });
run('swift', ['scripts/convert-original-photos.swift', source, temporary, manifest]);
const portraits = {};
let bytes = 0;
for (const entry of entries) {
  const png = join(temporary, `${entry.id}.png`);
  const dimensions = run('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', png]).toString();
  const width = Number(dimensions.match(/pixelWidth: (\d+)/)[1]);
  const height = Number(dimensions.match(/pixelHeight: (\d+)/)[1]);
  const variants = [];
  for (const size of [...new Set([360, 640, width].filter(size => size <= width))]) {
    const file = join(temporary, `${entry.id}-${size}.webp`);
    run('cwebp', ['-quiet', '-q', '90', '-m', '6', '-sharp_yuv', '-metadata', 'none', '-resize', String(size), '0', png, '-o', file]);
    const hash = createHash('sha256').update(readFileSync(file)).digest('hex').slice(0, 12);
    const name = `${entry.id}-${size}-${hash}.webp`;
    renameSync(file, join(output, name));
    bytes += statSync(join(output, name)).size;
    variants.push({ width: size, url: `media/originals/${name}` });
  }
  const placeholder = join(temporary, `${entry.id}-placeholder.webp`);
  run('cwebp', ['-quiet', '-q', '40', '-metadata', 'none', '-resize', '24', '0', png, '-o', placeholder]);
  portraits[entry.id] = {
    imageUrl: variants.at(-1).url, width, height,
    srcset: variants.map(variant => `${variant.url} ${variant.width}w`).join(', '),
    placeholder: `data:image/webp;base64,${readFileSync(placeholder).toString('base64')}`,
    objectPosition: entry.objectPosition
  };
}
writeFileSync('src/app/data/team-portraits.generated.ts', `// Generated by scripts/prepare-team-photos.mjs. Original uploads are untouched.\nexport const TEAM_PORTRAITS = ${JSON.stringify(portraits, null, 2)} as const;\n`);
console.log(`Prepared ${entries.length} team portrait: ${(bytes / 1024).toFixed(1)} KB across all responsive sizes.`);
