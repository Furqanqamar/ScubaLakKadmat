import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs';

mkdirSync('tmp/group-image-sizes', { recursive: true });
const info = {};
for (const name of ['boat', 'beach']) {
  const url = `media/team/team-group-${name}.jpg`, source = `public/${url}`;
  const dimensions = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', source]).toString();
  const width = Number(dimensions.match(/pixelWidth: (\d+)/)[1]);
  const height = Number(dimensions.match(/pixelHeight: (\d+)/)[1]);
  const variants = [];
  for (const w of [480, 640, 704, 800, 1024, 1280].filter(w => w < width)) {
    const temp = `tmp/group-image-sizes/${name}-${w}.webp`;
    execFileSync('cwebp', ['-quiet', '-q', '95', '-m', '6', '-sharp_yuv', '-metadata', 'none', '-resize', String(w), '0', source, '-o', temp]);
    const data = readFileSync(temp), hash = createHash('sha256').update(data).digest('hex').slice(0, 12);
    const file = `media/originals/team-group-${name}-${w}-${hash}.webp`;
    copyFileSync(temp, `public/${file}`);
    variants.push(`${file} ${w}w`);
  }
  variants.push(`${url} ${width}w`); // Unchanged highest-resolution original.
  info[url] = { width, height, srcset: variants.join(', ') };
}
writeFileSync('src/app/data/group-image-info.generated.ts', `// Generated by scripts/prepare-group-image-sizes.mjs; original JPGs remain intact.\nexport const GROUP_IMAGE_INFO: Readonly<Record<string, { readonly width: number; readonly height: number; readonly srcset: string }>> = ${JSON.stringify(info, null, 2)};\n`);
