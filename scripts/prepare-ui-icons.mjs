import { readFileSync, writeFileSync } from 'node:fs';

// Keep only the used vectors. Font Awesome Free 6.7.2 icons: CC BY 4.0.
const names = { solid: ['plus', 'location-arrow', 'arrow-left', 'image', 'play', 'star', 'arrow-up', 'location-dot', 'arrow-right', 'hotel', 'house'], brands: ['whatsapp', 'instagram'] };
const icons = {};
for (const [style, entries] of Object.entries(names)) for (const name of entries) {
  const svg = readFileSync(`node_modules/@fortawesome/fontawesome-free/svgs/${style}/${name}.svg`, 'utf8');
  icons[name] = { viewBox: svg.match(/viewBox="([^"]+)"/)[1], paths: [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map(match => match[1]) };
}
writeFileSync('src/app/data/ui-icons.generated.ts', `// Font Awesome Free 6.7.2, CC BY 4.0: https://fontawesome.com/license/free\n// Generated by scripts/prepare-ui-icons.mjs; no icon font is downloaded.\nexport const UI_ICONS: Readonly<Record<string, { readonly viewBox: string; readonly paths: readonly string[] }>> = ${JSON.stringify(icons)};\n`);
