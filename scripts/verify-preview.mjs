import assert from 'node:assert/strict';
const base = process.env.PREVIEW_URL ?? 'http://localhost:4004';
for (const path of ['/', '/about', '/courses', '/experiences', '/gallery', '/contact', '/lakshadweep', '/kadmat', '/lakshadweep/kadmat', '/lakshadweep/pitti-suheli', '/lakshadweep/pitti-bird']) {
  const response = await fetch(base + path);
  assert.equal(response.status, 200, path);
  assert.match(await response.text(), /<app-root/);
}
const homePage = await (await fetch(base + '/')).text();
const currentHero = homePage.match(/src="(media\/hero\/kadmat-desktop-[^"]+\.mp4)"/)?.[1];
assert.ok(currentHero);
const video = await fetch(`${base}/${currentHero}`, { headers: { Range: 'bytes=0-1023' } });
const legacySpots = await fetch(`${base}/kadmat-dive-sites`);
assert.equal(legacySpots.status, 200);
assert.match(await legacySpots.text(), /url=\/kadmat#dive-spots/);
assert.equal(video.status, 206);
assert.equal((await video.arrayBuffer()).byteLength, 1024);
const optimizedHero = await fetch(`${base}/${currentHero}`, { method: 'HEAD' });
assert.equal(optimizedHero.status, 200);
assert.match(optimizedHero.headers.get('cache-control') ?? '', /max-age=31536000, immutable/);
assert.equal(optimizedHero.headers.get('content-type'), 'video/mp4');
const galleryPage = await (await fetch(`${base}/gallery`)).text();
const suppliedImage = galleryPage.match(/src="(media\/originals\/lagoon-dive-group-[^"]+\.webp)"/)?.[1];
assert.ok(suppliedImage);
const suppliedPhoto = await fetch(`${base}/${suppliedImage}`, { method: 'HEAD' });
assert.equal(suppliedPhoto.status, 200);
assert.equal(suppliedPhoto.headers.get('content-type'), 'image/webp');
assert.match(suppliedPhoto.headers.get('cache-control') ?? '', /max-age=31536000, immutable/);
const suppliedEtag = suppliedPhoto.headers.get('etag');
assert.ok(suppliedEtag);
assert.equal((await fetch(`${base}/${suppliedImage}`, { headers: { 'If-None-Match': suppliedEtag } })).status, 304);
const currentLogo = galleryPage.match(/class="brand-lockup__logo"[^>]*src="([^"]+)"/)?.[1];
assert.ok(currentLogo?.startsWith('media/brand/'));
const logo = await fetch(`${base}/${currentLogo}`);
assert.equal(logo.status, 200);
assert.equal(logo.headers.get('content-type'), 'image/png');
assert.doesNotMatch(logo.headers.get('cache-control') ?? '', /immutable/);
const etag = logo.headers.get('etag');
assert.ok(etag);
await logo.body?.cancel();
assert.equal((await fetch(`${base}/${currentLogo}`, { headers: { 'If-None-Match': etag } })).status, 304);
const aboutPage = await (await fetch(`${base}/about`)).text();
const portraitPath = aboutPage.match(/src="(media\/originals\/amjad-khan-[^"]+\.webp)"/)?.[1];
assert.ok(portraitPath);
const portrait = await fetch(`${base}/${portraitPath}`, { method: 'HEAD' });
assert.equal(portrait.status, 200);
assert.equal(portrait.headers.get('content-type'), 'image/webp');
assert.match(portrait.headers.get('cache-control') ?? '', /max-age=31536000, immutable/);
const portraitEtag = portrait.headers.get('etag');
assert.ok(portraitEtag);
assert.equal((await fetch(`${base}/${portraitPath}`, { headers: { 'If-None-Match': portraitEtag } })).status, 304);
assert.equal((await fetch(`${base}/%ZZ`)).status, 400);
assert.equal((await fetch(`${base}/missing.webp`)).status, 404);
const unknownIsland = await fetch(`${base}/lakshadweep/not-an-island`);
assert.equal(unknownIsland.status, 404);
assert.match(await unknownIsland.text(), /noindex/);
const atlas = await (await fetch(`${base}/lakshadweep`)).text();
const islandImage = atlas.match(/src="(media\/islands\/[^\"]+\.webp)"/)?.[1];
assert.ok(islandImage);
const islandAsset = await fetch(`${base}/${islandImage}`, { method: 'HEAD' });
assert.equal(islandAsset.status, 200);
assert.equal(islandAsset.headers.get('content-type'), 'image/webp');
assert.match(islandAsset.headers.get('cache-control') ?? '', /max-age=31536000, immutable/);
console.log('Preview checks passed: routes, video ranges, cache revalidation, malformed URLs and missing files.');
